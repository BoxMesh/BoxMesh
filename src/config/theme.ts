// Status colours for inline props (Badge dots, Progress, Statistic, Timeline); they follow the active theme.
/** The browser's title-bar colour (`<meta name="theme-color">`), the page background of each theme. */
export const THEME_COLOR: Record<ThemeMode, string> = { dark: '#101416', light: '#ffffff' }

export const tone = {
  positive: 'var(--positive)',
  warning: 'var(--warning)',
  error: 'var(--error)',
  muted: 'var(--text-secondary)',
  disabled: 'var(--text-disabled)',
}

export function buildTheme(mode: ThemeMode): ThemeConfig {
  const p = palettes[mode]
  return {
    algorithm: mode === 'dark' ? theme.darkAlgorithm : theme.defaultAlgorithm,
    token: {
      colorPrimary: p.accent,
      colorPrimaryHover: p.accentHover,
      colorSuccess: p.success,
      colorSuccessBg: p.successBg,
      colorSuccessBorder: p.successBorder,
      colorWarning: p.warning,
      colorWarningBg: p.warningBg,
      colorWarningBorder: p.warningBorder,
      colorError: p.error,
      colorErrorBg: p.errorBg,
      colorErrorBorder: p.errorBorder,
      colorInfo: p.info,
      colorInfoBg: p.infoBg,
      colorInfoBorder: p.infoBorder,
      colorLink: p.accent,
      colorLinkHover: p.text,
      colorTextLightSolid: p.onSolid,
      colorText: p.text,
      colorTextSecondary: p.textSecondary,
      colorTextTertiary: p.textSecondary,
      colorTextPlaceholder: p.textSecondary,
      colorBgLayout: p.bgPage,
      colorBgContainer: p.bgSurface,
      colorBgElevated: mode === 'dark' ? p.bgRaised : p.bgSurface,
      colorBorder: p.borderControl,
      colorBorderSecondary: p.border,
      colorSplit: p.border,
      borderRadius: 12,
      borderRadiusLG: 16,
      borderRadiusSM: 10,
      controlHeight: 32,
      fontSize: 14,
      fontFamily: "Geist, 'Geist Fallback', -apple-system, 'Segoe UI', 'Hiragino Sans', 'Yu Gothic UI', Meiryo, Roboto, Arial, sans-serif",
      fontFamilyCode: "'Geist Mono', 'SFMono-Regular', Consolas, 'Liberation Mono', Menlo, monospace",
    },
    components: {
      Layout: {
        bodyBg: p.bgPage,
        siderBg: p.bgSurface,
        headerBg: p.bgSurface,
        headerHeight: 56,
        headerPadding: '0 24px',
        triggerBg: p.bgRaised,
        triggerColor: p.text,
      },
      // Compact sider: 32px rows (the control height), 12px inset. 13px text: at 14 the longest
      // label (Security & Certificates) no longer fits the 216px sider and gets cut.
      // The selected item stays a raised row with an accent icon rather than the canvas's filled block.
      Menu: {
        fontSize: 13,
        itemBg: 'transparent',
        itemColor: p.textSecondary,
        itemHoverColor: p.text,
        // Hover one step above the sider, the selected row a step above that, so neither hides the other.
        itemHoverBg: p.bgHover,
        itemSelectedBg: p.bgStrong,
        itemSelectedColor: p.text,
        itemActiveBg: p.bgHover,
        itemHeight: 32,
        itemBorderRadius: 12,
        itemMarginInline: 8,
        itemMarginBlock: 2,
        itemPaddingInline: 12,
        iconSize: 16,
        iconMarginInlineEnd: 10,
        groupTitleColor: p.textDisabled,
        groupTitleFontSize: 12,
        groupTitleLineHeight: '16px',
        activeBarBorderWidth: 0,
      },
      Button: {
        // Primary buttons are the tangerine brand fill: dark text on dark, white text on light.
        colorPrimary: p.brand,
        colorPrimaryHover: p.brandHover,
        colorPrimaryActive: p.brandHover,
        primaryColor: p.onBrand,
        fontWeight: 500,
        primaryShadow: p.primaryShadow,
        defaultBg: mode === 'dark' ? p.bgButton : p.bgSurface,
        defaultColor: p.text,
        defaultBorderColor: p.borderControl,
        defaultHoverBg: mode === 'dark' ? p.bgButton : p.bgSurface,
        defaultHoverColor: p.accent,
        defaultHoverBorderColor: p.accent,
        defaultShadow: p.defaultShadow,
        dangerShadow: p.dangerShadow,
      },
      // Compact scale: 16px inside cards, 12px between blocks (index.css), 8/12 in table cells.
      Card: { headerFontSize: 14, headerHeight: 44, headerPadding: 16, bodyPadding: 16 },
      Table: {
        headerBg: p.bgRaised,
        rowHoverBg: p.bgRaised,
        rowSelectedBg: p.successBg,
        rowSelectedHoverBg: p.rowSelectedHover,
        borderColor: p.border,
        headerSplitColor: 'transparent',
        headerBorderRadius: 0,
        cellFontSize: 14,
        cellPaddingBlock: 8,
        cellPaddingInline: 12,
      },
      Segmented: {
        trackBg: p.bgTrack,
        itemColor: p.textSecondary,
        itemSelectedBg: p.brand,
        itemSelectedColor: p.onBrand,
        trackPadding: 2,
      },
      Statistic: { contentFontSize: 26 },
      Alert: { defaultPadding: '8px 12px', withDescriptionPadding: '12px 16px' },
      Tag: { defaultBg: p.bgRaised, defaultColor: p.textSecondary, fontSizeSM: 12 },
      Descriptions: { labelColor: p.textSecondary, itemPaddingBottom: 12 },
      Progress: { remainingColor: p.bgTrack },
      Tooltip: { colorTextLightSolid: p.tooltipText, colorBgSpotlight: p.tooltipBg },
      // Orange box with an on-brand tick; the global borderRadiusSM (10) would turn the 16 px box into a circle.
      Switch: { colorPrimary: p.brand, colorPrimaryHover: p.brandHover },
      Checkbox: { colorPrimary: p.brand, colorPrimaryHover: p.brandHover, colorWhite: p.onBrand, borderRadiusSM: 4 },
    },
  }
}
